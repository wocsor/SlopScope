#!/usr/bin/env python3
"""Generate Q15 FFT coefficients from their mathematical definitions."""
import math
from pathlib import Path

POINTS = 1024


def bessel_i0(value):
    total = term = 1.0
    for order in range(1, 50):
        term *= (value / (2 * order)) ** 2
        total += term
        if term < total * 1e-16:
            break
    return total


def main():
    phase = [2 * math.pi * index / POINTS for index in range(POINTS)]
    windows = [
        [0.54 - 0.46 * math.cos(angle) for angle in phase],
        [1.0] * POINTS,
        [0.42 - 0.5 * math.cos(angle) + 0.08 * math.cos(2 * angle) for angle in phase],
        [0.5 - 0.5 * math.cos(angle) for angle in phase],
        [bessel_i0(6.5 * math.sqrt(max(0, 1 - (2 * index / POINTS - 1) ** 2))) /
         bessel_i0(6.5) for index in range(POINTS)],
        [1 - abs(2 * index / POINTS - 1) for index in range(POINTS)],
    ]
    quantize = lambda value: max(-32768, min(32767, round(value * 32768)))
    arrays = {
        'fft_cosine_q15': [quantize(math.cos(angle)) for angle in phase[:POINTS // 2]],
        'fft_sine_q15': [quantize(-math.sin(angle)) for angle in phase[:POINTS // 2]],
    }
    for index, window in enumerate(windows):
        arrays[f'fft_window_{index}_q15'] = [quantize(value) for value in window]
    lines = ['/* Generated by tools/generate_fft_tables.py from mathematical definitions. */',
             '#ifndef SCOPE_FFT_TABLES_H', '#define SCOPE_FFT_TABLES_H', '#include <stdint.h>']
    for name, values in arrays.items():
        lines.append(f'static const int16_t {name}[{len(values)}] = {{')
        lines.extend('    ' + ', '.join(map(str, values[start:start + 12])) + ','
                     for start in range(0, len(values), 12))
        lines.append('};')
    means = [round(sum(arrays[f'fft_window_{index}_q15']) / POINTS) for index in range(6)]
    lines.append('static const int16_t *const fft_windows_q15[] = {' +
                 ', '.join(f'fft_window_{index}_q15' for index in range(6)) + '};')
    lines.append('static const unsigned fft_window_mean_q15[] = {' + ', '.join(map(str, means)) + '};')
    lines.append('#endif')
    (Path(__file__).resolve().parents[1] / 'firmware/tables/fft_tables.h').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
